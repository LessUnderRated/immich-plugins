final _camel = RegExp(r'(?<=[a-z0-9])([A-Z])');

/// Normalizes `Icons.photo_library`, `photo-library`, `photoLibrary` and `PhotoLibrary` to `photo_library`.
String normalizePluginIconName(String name) {
  var value = name.trim();
  if (value.startsWith('Icons.')) {
    value = value.substring('Icons.'.length);
  }
  value = value.replaceAll('-', '_').replaceAllMapped(_camel, (match) => '_${match[1]}');
  return value.toLowerCase();
}

/// The icon for a plugin icon name, or null when the name is unknown (or is a file).
IconData? pluginIconData(String? name) {
  if (name == null || name.isEmpty) {
    return null;
  }
  final exact = pluginLegacyIcons[name] ?? pluginMaterialIcons[name];
  if (exact != null) {
    return exact;
  }
  final normalized = normalizePluginIconName(name);
  final found = pluginLegacyIcons[normalized] ?? pluginMaterialIcons[normalized];
  if (found != null) {
    return found;
  }
  for (final suffix in const ['_rounded', '_sharp', '_outline', '_filled', '_outlined']) {
    if (normalized.endsWith(suffix)) {
      final base = normalized.substring(0, normalized.length - suffix.length);
      return pluginMaterialIcons['${base}_outlined'] ?? pluginMaterialIcons[base];
    }
  }
  return null;
}

/// Whether an icon value names a file shipped in the plugin zip (or an absolute path) rather than a Material icon.
bool isPluginIconFile(String icon) => icon.contains('.') || icon.contains('/');

/// Resolves a plugin file path: absolute paths stay, relative ones point into the plugin's shipped files.
String resolvePluginFile(String pluginsRoot, String plugin, String path) =>
    p.isAbsolute(path) ? path : p.join(pluginsRoot, plugin, 'files', path);

/// A plugin icon: a Material icon name (see [pluginIconData]), or an image file shipped in the plugin zip.
/// Unknown names show the extension icon.
class PluginIcon extends ConsumerWidget {
  final String plugin;
  final String? icon;
  final Color? color;
  final double? size;

  const PluginIcon({super.key, required this.plugin, this.icon, this.color, this.size});

  @override
  Widget build(BuildContext context, WidgetRef ref) {
    final icon = this.icon;
    if (icon != null && isPluginIconFile(icon)) {
      final root = ref.watch(pluginFilesRootProvider).valueOrNull;
      final size = this.size ?? IconTheme.of(context).size ?? 24;
      if (root == null) {
        return SizedBox.square(dimension: size);
      }
      return Image.file(
        File(resolvePluginFile(root, plugin, icon)),
        width: size,
        height: size,
        color: color,
        errorBuilder: (_, _, _) => Icon(Icons.extension_outlined, color: color, size: size),
      );
    }
    return Icon(pluginIconData(icon) ?? Icons.extension_outlined, color: color, size: size);
  }
}
